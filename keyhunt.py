#!/usr/bin/env python3
"""Hunt the AES-256 key in the traffic-time full dump.

Strategy, in order of cheap to expensive:
 1. Slice +-2MB around every `sign=` hit (16 of them). The key is used by the
    same request path, so it is likely to sit in nearby heap.
 2. Entropy prefilter: 32-byte windows with >=26 distinct byte values.
 3. AES-256 key-schedule verify on survivors: expand the candidate 32 bytes
    and check the next bytes match the schedule. A match is near-certain key.
Hits (offset, entropy, schedule_ok) are printed; the 1KB neighbourhood of each
schedule match is saved to /tmp/live-res/seg/key_cand_<off>.bin
"""
