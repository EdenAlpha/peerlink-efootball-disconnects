def sub_word(w):
    return bytes(SBOX[b] for b in w)


def rot_word(w):
    return w[1:] + w[:1]


def xtime(a):
    return ((a << 1) ^ 0x1B) & 0xFF if a & 0x80 else (a << 1) & 0xFF


def expand32(key):
    # returns first 64 bytes of the AES-256 schedule (key + round1)
    w = [key[i:i + 4] for i in range(0, 32, 4)]
    out = bytearray(key)
    for i in range(8, 16):
        t = w[i - 1]
        if i % 8 == 0:
            t = bytes([sub_word(rot_word(t))[j] ^ (RCON[i // 8 - 1] if j == 0 else 0)
                       for j in range(4)])
        elif i % 8 == 4:
            t = sub_word(t)
        wi = bytes([w[i - 8][j] ^ t[j] for j in range(4)])
        w.append(wi)
        out += wi
    return bytes(out)


def main():
    import subprocess
    out = subprocess.run(["grep", "-abo", "-F", "sign=", FULL],
                         capture_output=True, timeout=600).stdout.decode()
    sign_offs = [int(l.split(":")[0]) for l in out.splitlines() if ":" in l]
    print("sign= hits: %d" % len(sign_offs))
    f = open(FULL, "rb")
    f.seek(0, 2)
    size = f.tell()
    # windows +-2MB around each hit, merged
    wins = set()
    for o in sign_offs:
        a = max(0, (o - (1 << 21)) // (1 << 16))
        b = min(size, (o + (1 << 21))) // (1 << 16)
        for k in range(a, b + 1):
            wins.add(k)
    print("64KB blocks to scan: %d (%.0f MB)" % (len(wins), len(wins) / 16.0))
    n_cand = n_sched = 0
    for bi, k in enumerate(sorted(wins)):
        f.seek(k * (1 << 16))
        blk = f.read(1 << 16)
        for o in range(0, len(blk) - 32, 16):
            w = blk[o:o + 32]
            if all(32 <= x < 127 for x in w):
                continue
            if len(set(w)) < 26:
                continue
            n_cand += 1
            try:
                sched = expand32(w)
            except Exception:
                continue
            if blk[o + 32:o + 64] == sched[32:64]:
                n_sched += 1
                goff = k * (1 << 16) + o
                print("SCHEDULE MATCH at fileoff %d (0x%x) ent=%d: %s"
                      % (goff, goff, len(set(w)), w.hex()))
                open("%s/key_cand_%d.bin" % (OUT, goff), "wb").write(blk[max(0, o - 512):o + 1024])
        if bi % 200 == 0:
            print("  ... %d/%d blocks, cands=%d sched=%d" % (bi, len(wins), n_cand, n_sched))
    print("DONE cands=%d schedule_matches=%d" % (n_cand, n_sched))


main()